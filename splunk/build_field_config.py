#!/usr/bin/env python3
"""Generate every field-level Splunk/Cribl config from btc_parser_app/export_schema.py.

    python splunk/build_field_config.py          # (re)write the generated files
    python splunk/build_field_config.py --check  # exit 1 if any is out of date

Generated files (do not edit by hand - edit export_schema.py and re-run):

- TA-btc-parser-parsing/default/{props,transforms}.conf - index time, for an
  instance that reads the CSVs itself (the standalone test instance).
  Small sourcetypes: INDEXED_EXTRACTIONS = csv. transactions/inputs/outputs:
  classic line breaking + positional timestamp, header row to nullQueue,
  one WRITE_META transform per indexed column.
- TA-btc-parser-search/default/{props,transforms,fields}.conf - search time,
  every environment: positional REGEX extraction of the non-indexed
  columns, fields.conf INDEXED = true for the indexed ones.
- ../cribl/btc_parser_pipeline.json - prod (UF -> Cribl -> Splunk): Cribl
  delivers events already parsed, so Splunk applies no index-time props;
  the pipeline does the same job (drop header, set _time, keep only the
  indexed columns as event fields - every top-level field Cribl sends
  becomes an indexed field).

See docs/10-splunk-integration-und-feldkonzept.md 10.6.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

SPLUNK_DIR = Path(__file__).resolve().parent
REPO_ROOT = SPLUNK_DIR.parent
sys.path.insert(0, str(REPO_ROOT))

from btc_parser_app.export_schema import SOURCETYPES, Sourcetype  # noqa: E402

GENERATED_NOTE = "# Generated by splunk/build_field_config.py from btc_parser_app/export_schema.py - edit those, not this file."

# Splunk's default (2000 days) rejects every timestamp before ~2021;
# 10951 is the maximum. Genesis is 2009-01-03.
MAX_DAYS_AGO = 10951


def _short(st: Sourcetype) -> str:
    return st.name.split(":", 1)[1]


def _skip_columns_regex(n: int) -> str:
    """Anchored regex that skips the first n CSV columns. [^,]* cannot eat a
    comma, so the match is pinned to exactly that column - no backtracking
    onto a later one."""
    return "^" if n == 0 else f"^(?:[^,]*,){{{n}}}"


def _check_index_consistency() -> list[str]:
    """fields.conf INDEXED = true is global: a name indexed in one
    sourcetype must be indexed everywhere it appears as a column, or
    `field=value` silently finds nothing in the others."""
    errors = []
    for st in SOURCETYPES:
        if st.indexed is None:
            continue
        for field in st.indexed:
            if field not in st.columns:
                errors.append(f"{st.name}: indexed field {field!r} is not a column")
            for other in SOURCETYPES:
                if field in other.columns and field not in other.indexed_fields:
                    errors.append(
                        f"{field!r} is indexed in {st.name} but not in {other.name} - "
                        "index it in both or in neither (fields.conf is global)"
                    )
    return errors


# --- index time (standalone/test instance) ---------------------------------

INDEX_PROPS_HEADER = f"""{GENERATED_NOTE}
#
# TA-btc-parser-parsing/default/props.conf - INDEX TIME.
#
# Install on the Splunk instance that READS the CSVs: the standalone test
# instance (parser, inputs and Splunk Enterprise on one host). It has no
# effect in prod (UF -> Cribl -> Splunk Enterprise): Cribl hands Splunk
# already-parsed events, so Splunk skips its parsing/typing for them - the
# same work is done by cribl/btc_parser_pipeline.json there. Never install
# it on a Universal Forwarder: INDEXED_EXTRACTIONS would make the UF parse
# the small sourcetypes and ship every column to Cribl as an indexed field.
#
# Field concept (docs/10-splunk-integration-und-feldkonzept.md 10.6):
# - btc:blocks, btc:stale_block_headers, btc:sanctioned_tx_events,
#   btc:prices: INDEXED_EXTRACTIONS = csv, every column an indexed field.
# - btc:transactions, btc:inputs, btc:outputs: no INDEXED_EXTRACTIONS.
#   Classic line breaking, _time from the block_time column by position,
#   header row to nullQueue, and one WRITE_META transform per indexed
#   column (transforms.conf). Everything else is extracted at search time
#   by TA-btc-parser-search. Column positions come from export_schema.py,
#   which tests/test_export_schema.py pins to the rows block_parser.py
#   writes.
#
# MAX_DAYS_AGO = {MAX_DAYS_AGO} (the maximum) on every sourcetype: the default
# of 2000 days would give every pre-2021 event a fallback _time.
# ANNOTATE_PUNCT = false: punct:: means nothing for CSV rows and costs
# index-time CPU and tsidx space on billions of events.
"""


def _index_props_structured(st: Sourcetype) -> list[str]:
    return [
        f"[{st.name}]",
        "INDEXED_EXTRACTIONS = csv",
        "HEADER_FIELD_LINE_NUMBER = 1",
        "FIELD_DELIMITER = ,",
        'FIELD_QUOTE = "',
        f"TIMESTAMP_FIELDS = {st.time_field}",
        f"TIME_FORMAT = {st.time_format}",
        "TZ = UTC",
        "SHOULD_LINEMERGE = false",
        f"MAX_DAYS_AGO = {MAX_DAYS_AGO}",
        "ANNOTATE_PUNCT = false",
        "category = Structured",
        f"description = {st.description}",
    ]


def _index_transform_names(st: Sourcetype) -> list[str]:
    return [f"btc_idx_{_short(st)}_{field}" for field in st.indexed_fields]


def _index_props_positional(st: Sourcetype) -> list[str]:
    time_pos = st.columns.index(st.time_field)
    return [
        f"[{st.name}]",
        "SHOULD_LINEMERGE = false",
        "LINE_BREAKER = ([\\r\\n]+)",
        f"TIME_PREFIX = {_skip_columns_regex(time_pos)}",
        f"TIME_FORMAT = {st.time_format}",
        "MAX_TIMESTAMP_LOOKAHEAD = 10",
        "TZ = UTC",
        f"MAX_DAYS_AGO = {MAX_DAYS_AGO}",
        "ANNOTATE_PUNCT = false",
        f"TRANSFORMS-btc_00_header = btc_drop_header_{_short(st)}",
        f"TRANSFORMS-btc_10_indexed = {', '.join(_index_transform_names(st))}",
        "category = Structured",
        f"description = {st.description}",
    ]


def index_props() -> str:
    blocks = [
        _index_props_structured(st) if st.indexed is None else _index_props_positional(st)
        for st in SOURCETYPES
    ]
    return INDEX_PROPS_HEADER + "\n" + "\n\n".join("\n".join(b) for b in blocks) + "\n"


def index_transforms() -> str:
    out = [
        GENERATED_NOTE,
        "#",
        "# TA-btc-parser-parsing/default/transforms.conf - INDEX TIME, see props.conf.",
        "#",
        "# btc_idx_<sourcetype>_<field>: pins the regex to that field's column",
        "# (export_schema.py) and requires a non-empty value - an empty CSV",
        "# value (null, e.g. prevout_type on a coinbase input) writes no indexed",
        "# field at all instead of an empty one.",
    ]
    for st in SOURCETYPES:
        if st.indexed is None:
            continue
        out += [
            "",
            f"[btc_drop_header_{_short(st)}]",
            f"REGEX = ^{st.header_prefix}",
            "DEST_KEY = queue",
            "FORMAT = nullQueue",
        ]
        for field, name in zip(st.indexed_fields, _index_transform_names(st)):
            out += [
                "",
                f"[{name}]",
                f"REGEX = {_skip_columns_regex(st.columns.index(field))}([^,]+)",
                f"FORMAT = {field}::$1",
                "WRITE_META = true",
            ]
    return "\n".join(out) + "\n"


# --- search time (every environment) ---------------------------------------

def search_props() -> str:
    out = [
        GENERATED_NOTE,
        "#",
        "# TA-btc-parser-search/default/props.conf - SEARCH TIME.",
        "#",
        "# Install on the search head(s): the standalone test instance, and",
        "# the prod search tier. Indexed fields come back with each event",
        "# without any extraction; the REPORT below only extracts the columns",
        "# that are not indexed (an indexed column extracted again at search",
        "# time would turn into a duplicated multivalue field). KV_MODE = none:",
        "# CSV rows hold no key=value pairs worth auto-extracting.",
    ]
    for st in SOURCETYPES:
        out += ["", f"[{st.name}]", "KV_MODE = none", "AUTO_KV_JSON = false"]
        if st.search_time_fields:
            out.append(f"REPORT-btc_columns = btc_columns_{_short(st)}")
    return "\n".join(out) + "\n"


def search_transforms() -> str:
    out = [
        GENERATED_NOTE,
        "#",
        "# TA-btc-parser-search/default/transforms.conf - SEARCH TIME, see props.conf.",
        "#",
        "# One anchored regex per sourcetype over the whole CSV row: a named",
        "# group per search-time column, [^,]* for indexed ones (skipped). These",
        "# rows never contain quoted values (hashes, numbers, booleans, script",
        "# types, addresses), so splitting on every comma is exact. Empty",
        "# values (nulls) produce no field.",
    ]
    for st in SOURCETYPES:
        if not st.search_time_fields:
            continue
        parts = [
            f"(?<{c}>[^,]*)" if c in st.search_time_fields else "[^,]*" for c in st.columns
        ]
        out += ["", f"[btc_columns_{_short(st)}]", "REGEX = ^" + ",".join(parts)]
    return "\n".join(out) + "\n"


def search_fields() -> str:
    out = [
        GENERATED_NOTE,
        "#",
        "# TA-btc-parser-search/default/fields.conf - SEARCH TIME.",
        "#",
        "# INDEXED = true makes `field=value` look up the indexed term",
        "# field::value instead of the raw token `value` - which matters for",
        "# exactly these fields: their values (true, false, 2, 1, ...) also",
        "# appear in many other columns, so a raw-term lookup narrows nothing.",
        "# Only the explicitly indexed transactions/inputs/outputs columns are",
        "# listed; the INDEXED_EXTRACTIONS sourcetypes need no entry. Global",
        "# setting - see the consistency rule in export_schema.py.",
    ]
    names: list[str] = []
    for st in SOURCETYPES:
        if st.indexed is not None:
            names += [f for f in st.indexed if f not in names]
    for name in names:
        out += ["", f"[{name}]", "INDEXED = true"]
    return "\n".join(out) + "\n"


# --- Cribl (prod) ------------------------------------------------------------

def _js_str(value: str) -> str:
    return json.dumps(value)


def cribl_pipeline() -> str:
    header_checks = " || ".join(
        f"(sourcetype=={_js_str(st.name)} && _raw.startsWith({_js_str(st.header_prefix)}))"
        for st in SOURCETYPES
    )
    functions: list[dict] = [
        {
            "id": "comment",
            "conf": {
                "comment": (
                    "Generated by splunk/build_field_config.py from btc_parser_app/export_schema.py "
                    "- re-generate and re-import instead of editing. Every top-level field left on "
                    "the event becomes an indexed field in Splunk; _raw stays the CSV row and the "
                    "rest is extracted at search time by TA-btc-parser-search."
                )
            },
        },
        {
            "id": "drop",
            "filter": header_checks,
            "description": "CSV header rows (one per part file)",
            "conf": {},
        },
    ]
    for st in SOURCETYPES:
        is_st = f"sourcetype=={_js_str(st.name)}"
        keep = list(st.indexed_fields)
        if st.time_field not in keep:
            keep.append(st.time_field)
        parser_conf: dict = {
            "mode": "extract",
            "type": "csv",
            "srcField": "_raw",
            "fields": list(st.columns),
        }
        if st.indexed is not None:
            parser_conf["keep"] = keep
        functions.append(
            {
                "id": "serde",
                "filter": is_st,
                "description": f"{st.name}: extract "
                + ("every column" if st.indexed is None else ", ".join(st.indexed)),
                "conf": parser_conf,
            }
        )
        if st.time_format == "%s":
            time_expr = f"Number({st.time_field})"
        else:
            time_expr = f"Date.parse({st.time_field}) / 1000"
        eval_conf: dict = {"add": [{"name": "_time", "value": time_expr}]}
        if st.time_field not in st.indexed_fields:
            eval_conf["remove"] = [st.time_field]
        functions.append(
            {
                "id": "eval",
                "filter": is_st,
                "description": f"{st.name}: _time from {st.time_field}",
                "conf": eval_conf,
            }
        )
    functions.append(
        {
            "id": "code",
            "filter": "sourcetype.startsWith('btc:')",
            "description": "Drop empty CSV values (nulls) instead of sending empty indexed fields",
            "conf": {
                "code": "for (const k of Object.keys(__e)) { if (__e[k] === '') delete __e[k]; }",
                "maxNumOfIterations": 5000,
            },
        }
    )
    pipeline = {
        "id": "btc_parser",
        "conf": {
            "output": "default",
            "streamtags": [],
            "groups": {},
            "asyncFuncTimeout": 1000,
            "description": "btc_parser_app export CSVs -> Splunk (docs chapter 10.6)",
            "functions": functions,
        },
    }
    return json.dumps(pipeline, indent=2) + "\n"


def generated_files() -> dict[Path, str]:
    errors = _check_index_consistency()
    if errors:
        raise SystemExit("export_schema.py is inconsistent:\n  " + "\n  ".join(errors))
    return {
        SPLUNK_DIR / "TA-btc-parser-parsing/default/props.conf": index_props(),
        SPLUNK_DIR / "TA-btc-parser-parsing/default/transforms.conf": index_transforms(),
        SPLUNK_DIR / "TA-btc-parser-search/default/props.conf": search_props(),
        SPLUNK_DIR / "TA-btc-parser-search/default/transforms.conf": search_transforms(),
        SPLUNK_DIR / "TA-btc-parser-search/default/fields.conf": search_fields(),
        REPO_ROOT / "cribl/btc_parser_pipeline.json": cribl_pipeline(),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if any generated file is out of date")
    args = parser.parse_args()

    stale = []
    for path, content in generated_files().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(REPO_ROOT)}")
    if args.check and stale:
        print("Out of date (run python splunk/build_field_config.py):")
        for path in stale:
            print(f"  {path.relative_to(REPO_ROOT)}")
        return 1
    if not stale:
        print("all generated files up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
